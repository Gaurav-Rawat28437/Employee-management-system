
const mongoose = require("mongoose")

const employeeSchema = new mongoose.Schema(
    {
        employeeName: {
            type: String,
            required: true,
            trim: true
        },

        email: {
            type: String,
            required: true,
            unique: true,
            lowercase: true,
            trim: true
        },

        phoneNumber: {
            type: String,
            required: true,
            trim: true
        },

        department: {
            type: String,
            required: true,
            trim: true
        },

        designation: {
            type: String,
            required: true,
            trim: true
        },

        joiningDate: {
            type: Date,
            required: true,
        },

        status: {
            type: String,
            enum: ["Active", "Inactive"],
            default: "Active"
        }
    },
    {
        timestamps: true
    }
)

const Employee = mongoose.model("Employee", employeeSchema)

module.exports = Employee
